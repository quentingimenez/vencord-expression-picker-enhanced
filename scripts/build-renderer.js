"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const PARTS_DIR = path.join(ROOT, "src", "renderer");
const OUTPUT_PATH = path.join(ROOT, "dist", "picker-resize.js");
const BANNER = "/* Generated by scripts/build-renderer.js. Do not edit this file directly. */\n";

/**
 * The renderer is injected as a single script, so the build concatenates the
 * source fragments inside one IIFE. Keeping the fragments separate makes the
 * source navigable while preserving the one-file delivery constraint.
 */
const PART_FILES = [
    "00-header.js",
    "02-gifenc.js",
    "01-guard.js",
    "03-core.js",
    "04-resize.js",
    "05-imports-constants.js",
    "06-messages.js",
    "07-i18n.js",
    "08-imports-core.js",
    "09-imports-ui.js",
    "10-imports-view.js",
    "11-imports-favorites.js",
    "12-imports-maintenance.js",
    "13-imports-actions.js",
    "14-imports-conversion.js",
    "15-imports-styles.js",
    "16-main.js"
];

function readPart(name) {
    const file = path.join(PARTS_DIR, name);
    if (!fs.existsSync(file)) throw new Error(`Missing renderer part: ${name}`);
    return fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").trimEnd();
}

function checkPartList() {
    const actual = fs
        .readdirSync(PARTS_DIR)
        .filter((name) => name.endsWith(".js"))
        .sort();
    const expected = [...PART_FILES].sort();
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
        throw new Error(
            `Renderer parts are out of sync.\nExpected: ${expected.join(", ")}\nActual:   ${actual.join(", ")}`
        );
    }
}

function renderBundle() {
    const header = readPart("00-header.js");
    const vendor = readPart("02-gifenc.js");
    const guard = readPart("01-guard.js");
    const body = PART_FILES.filter((name) => !["00-header.js", "01-guard.js", "02-gifenc.js"].includes(name)).map(
        readPart
    );

    const inside = [
        guard,
        "    if (!isDiscordHost) return;",
        "    if (window[INSTALL_FLAG]) return;",
        "    window[INSTALL_FLAG] = true;",
        ...body
    ].join("\n\n");

    return `${BANNER}\n${header}\n\n${vendor}\n\n(() => {\n    "use strict";\n\n${inside}\n})();\n`;
}

function build({ check = false } = {}) {
    checkPartList();
    const output = renderBundle();
    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });

    if (check) {
        if (!fs.existsSync(OUTPUT_PATH) || fs.readFileSync(OUTPUT_PATH, "utf8") !== output) {
            throw new Error(`${path.relative(ROOT, OUTPUT_PATH)} is outdated. Run npm run build.`);
        }
        return { output, bytes: Buffer.byteLength(output) };
    }

    fs.writeFileSync(OUTPUT_PATH, output, "utf8");
    return { output, bytes: Buffer.byteLength(output) };
}

if (require.main === module) {
    const result = build({ check: process.argv.includes("--check") });
    const relative = path.relative(ROOT, OUTPUT_PATH).replace(/\\/g, "/");
    console.log(`${process.argv.includes("--check") ? "Verified" : "Built"} ${relative} (${result.bytes} bytes)`);
}

module.exports = {
    PART_FILES,
    PARTS_DIR,
    OUTPUT_PATH,
    build,
    renderBundle
};
